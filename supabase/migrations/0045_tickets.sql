-- 0045_tickets — phase 8 «تذاكر الفريق» on real data (docs/superpowers/plans/2026-11-05-phase-8-tickets.md).
-- A ticket is assigned to a role (decision 1), carries a timeline that only grows (ticket_events: a message or an event), and every
-- change goes through one RPC that applies the v2 domain's rules (block 05) on the server, writing its event in the same
-- transaction (decision 5):
-- * ticket_create(p_input) — tickets.manage F; the v2's validateTicket (type, title ≤ 80, description, priority, the role, a
--   customer ticket's order number + reason, a maker ticket's maker + reason, the follow-up date) + the attachments (decision 2).
-- * ticket_act(p_id, p_action, p_args) — set_status (in_progress / waiting) · resolve (an outcome) · close · reopen (a reason) ·
--   update (assigneeRole / priority / followUp) · reply (text + attachments). Working on a ticket (status / resolve) = the admin or a
--   member of the role it is assigned to; closing and reopening = the admin or the one who opened it; update = either; a closed
--   ticket takes no reply and no status; reopening needs a reason and goes back to the role.
-- * The roles (decision 1 + 14): مدير النظام = admin · خدمة العملاء = cs · متابعة المبتكرين = vendors_followup · الحسابات = accounts ·
--   اللوجستيك والشحن and المحتوى والتصوير = ops.
-- * Permissions (decision 4): tickets.view F = every ticket, P = my role's tickets + the ones I opened; tickets.manage F = open,
--   reply and work on what I see. Admin F/F; ops, cs F/F; vendors_followup, accounts P/F; viewer P/N.
-- * No delete (decision 13): nothing deletes a ticket or an event for a member; a mistake is closed «مكرر» / «مش مشكلة».
-- * Links (decisions 3 + 11): the order (the number typed + the orders row when it exists), the customer (cs_customers, from the
--   order's phone or the conversation), the maker (vendors), the customer-service conversation.
-- * Attachments (decision 2): images and PDF, ≤ 10 per ticket / reply, 10 MB each, in the private bucket «tickets» under the
--   uploader's own folder (<uid>/…); a member reads a file of a ticket they see (or their own uploads).
-- * Live (decision 9): every write on tickets / ticket_events sends one private Realtime broadcast «tickets» / «changed» with
--   { at } only; members with tickets.view ≠ N receive it and fetch through their own RLS.
-- Re-runnable.

update public.roles r set permissions = r.permissions || d.perms
from (values
  ('admin',            '{"tickets.view":"F","tickets.manage":"F"}'::jsonb),
  ('ops',              '{"tickets.view":"F","tickets.manage":"F"}'::jsonb),
  ('cs',               '{"tickets.view":"F","tickets.manage":"F"}'::jsonb),
  ('vendors_followup', '{"tickets.view":"P","tickets.manage":"F"}'::jsonb),
  ('accounts',         '{"tickets.view":"P","tickets.manage":"F"}'::jsonb),
  ('viewer',           '{"tickets.view":"P","tickets.manage":"N"}'::jsonb)
) as d(id, perms)
where r.id = d.id and (r.permissions -> 'tickets.view', r.permissions -> 'tickets.manage') is distinct from (d.perms -> 'tickets.view', d.perms -> 'tickets.manage');

-- ---------------------------------------------------------------- the roles a ticket is assigned to

create or replace function public.ticket_role_labels(p_role text) returns text[]
language sql immutable set search_path = public as $$
  select case p_role
    when 'admin' then array['مدير النظام']
    when 'cs' then array['خدمة العملاء']
    when 'vendors_followup' then array['متابعة المبتكرين']
    when 'accounts' then array['الحسابات']
    when 'ops' then array['اللوجستيك والشحن', 'المحتوى والتصوير']
    else '{}'::text[] end
$$;

-- the ticket roles of the signed-in member (an inactive member has none)
create or replace function public.ticket_my_roles() returns text[]
language sql stable security definer set search_path = public as $$
  select coalesce((select public.ticket_role_labels(p.role_id) from public.profiles p where p.id = auth.uid() and p.status = 'active'), '{}'::text[])
$$;

-- tickets.view F = all; P = assigned to my role or opened by me
create or replace function public.ticket_can_see(p_role text, p_by uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select case public.has_perm('tickets.view')
    when 'F' then true
    when 'P' then (p_by is not null and p_by = auth.uid()) or p_role = any (public.ticket_my_roles())
    else false end
$$;

-- the v2's clean(): control characters → space, whitespace collapsed, trimmed, cut
create or replace function public.ticket_clean(s text, n int) returns text
language sql immutable set search_path = public as $$
  select left(btrim(regexp_replace(regexp_replace(coalesce(s, ''), '[\x01-\x1f\x7f]', ' ', 'g'), '\s+', ' ', 'g')), n)
$$;

-- ---------------------------------------------------------------- tables

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('customer', 'vendor', 'internal')),
  title text not null check (char_length(title) between 1 and 80),
  description text not null check (char_length(description) between 1 and 5000),
  priority text not null check (priority in ('urgent', 'high', 'normal', 'low')),
  assignee_role text not null check (assignee_role in ('مدير النظام', 'خدمة العملاء', 'متابعة المبتكرين', 'الحسابات', 'اللوجستيك والشحن', 'المحتوى والتصوير')),
  order_number text check (order_number is null or char_length(order_number) between 1 and 20),
  order_id bigint references public.orders on delete set null,
  customer text check (customer is null or char_length(customer) <= 80),
  cs_customer_id uuid references public.cs_customers on delete set null,
  cs_conversation_id uuid references public.cs_conversations on delete set null,
  vendor_id uuid references public.vendors on delete set null,
  vendor text check (vendor is null or char_length(vendor) <= 80),
  reason text check (reason is null or char_length(reason) <= 60),
  follow_up date,
  attachments jsonb not null default '[]'::jsonb check (jsonb_typeof(attachments) = 'array' and jsonb_array_length(attachments) <= 10),
  status text not null default 'open' check (status in ('open', 'in_progress', 'waiting', 'resolved', 'closed')),
  created_by uuid references public.profiles on delete set null,
  created_by_name text not null check (char_length(created_by_name) <= 120),
  created_by_role text not null check (char_length(created_by_role) <= 60),
  created_at timestamptz not null default now(),
  last_update timestamptz not null default now(),
  reopen_count int not null default 0 check (reopen_count >= 0),
  resolution_outcome text check (resolution_outcome is null or resolution_outcome in ('اتحلت المشكلة', 'مش مشكلة', 'مكرر', 'العميل / المبتكر ما ردش')),
  resolution_note text check (resolution_note is null or char_length(resolution_note) <= 1000),
  resolved_by uuid references public.profiles on delete set null,
  resolved_by_name text check (resolved_by_name is null or char_length(resolved_by_name) <= 120),
  resolved_at timestamptz,
  closed_by uuid references public.profiles on delete set null,
  closed_by_name text check (closed_by_name is null or char_length(closed_by_name) <= 120),
  closed_at timestamptz,
  constraint tickets_customer check (type <> 'customer' or (order_number is not null and reason in ('تأخير في التسليم', 'منتج تالف', 'منتج مختلف عن الطلب', 'مشكلة دفع أو استرجاع', 'العميل مش بيرد', 'أخرى'))),
  constraint tickets_vendor check (type <> 'vendor' or (vendor is not null and reason in ('تأخير تسليم', 'جودة', 'خامة ناقصة', 'خلاف على الحساب أو العمولة', 'مش بيرد', 'أخرى')))
);
create index if not exists tickets_status_idx on public.tickets (status, last_update desc);
create index if not exists tickets_order_idx on public.tickets (order_id) where order_id is not null;
create index if not exists tickets_vendor_idx on public.tickets (vendor_id) where vendor_id is not null;
create index if not exists tickets_customer_idx on public.tickets (cs_customer_id) where cs_customer_id is not null;
create index if not exists tickets_conversation_idx on public.tickets (cs_conversation_id) where cs_conversation_id is not null;

create table if not exists public.ticket_events (
  id bigserial primary key,
  ticket_id bigint not null references public.tickets on delete cascade,
  kind text not null check (kind in ('message', 'event')),
  at timestamptz not null default now(),
  actor uuid references public.profiles on delete set null,
  actor_name text not null check (char_length(actor_name) <= 120),
  actor_role text not null check (char_length(actor_role) <= 60),
  text text not null check (char_length(text) between 1 and 7000),
  old_value text check (old_value is null or char_length(old_value) <= 80),
  new_value text check (new_value is null or char_length(new_value) <= 80),
  attachments jsonb not null default '[]'::jsonb check (jsonb_typeof(attachments) = 'array' and jsonb_array_length(attachments) <= 10)
);
create index if not exists ticket_events_ticket_idx on public.ticket_events (ticket_id, at, id);

alter table public.tickets enable row level security;
alter table public.ticket_events enable row level security;

drop policy if exists tickets_select on public.tickets;
create policy tickets_select on public.tickets for select to authenticated
  using ((select public.ticket_can_see(assignee_role, created_by)));
drop policy if exists ticket_events_select on public.ticket_events;
create policy ticket_events_select on public.ticket_events for select to authenticated
  using (exists (select 1 from public.tickets t where t.id = ticket_id)); -- the tickets policy applies inside

-- members read; every write is the RPCs' (security definer) — no insert / update / delete for a member
revoke all on public.tickets, public.ticket_events from anon, authenticated;
grant select on public.tickets, public.ticket_events to authenticated;
grant all on public.tickets, public.ticket_events to service_role;
