-- ---------------------------------------------------------------- live line (decision 9): private broadcast «tickets» / «changed», { at } only

create or replace function public.tickets_notify() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if to_regprocedure('realtime.send(jsonb, text, text, boolean)') is not null then
    begin
      execute 'select realtime.send($1, $2, $3, $4)' using jsonb_build_object('at', now()), 'changed', 'tickets', true;
    exception when others then null; -- the write goes on; the pages' periodic check picks it up
    end;
  end if;
  return null;
end $$;
revoke execute on function public.tickets_notify() from public, anon, authenticated;

drop trigger if exists tickets_notify on public.tickets;
create trigger tickets_notify after insert or update on public.tickets for each statement execute function public.tickets_notify();
drop trigger if exists ticket_events_notify on public.ticket_events;
create trigger ticket_events_notify after insert on public.ticket_events for each statement execute function public.tickets_notify();

do $$
